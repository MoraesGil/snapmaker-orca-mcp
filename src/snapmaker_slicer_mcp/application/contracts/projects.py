"""Capabilities required by project use cases, independent of 3MF storage."""
from __future__ import annotations
from contextlib import AbstractContextManager
from typing import Protocol
from ...domain.types.json import JsonObject, JsonValue
from .presets import EngineIdentity

class ProjectDocument(Protocol):
    @property
    def config(self) -> JsonObject: ...
    def describe(self) -> JsonObject: ...
    def get_config(self, keys: list[str] | None = None) -> JsonObject: ...
    def list_objects(self) -> list[JsonValue]: ...
    def list_plates(self) -> list[JsonValue]: ...
    def execute(self, name: str, arguments: JsonObject) -> JsonValue: ...

class RevisionRepository(Protocol):
    def transaction(self) -> AbstractContextManager[object]: ...
    def load(self, path: str, identity: JsonObject) -> JsonObject: ...
    def state(self, project_id: str) -> JsonObject: ...
    def open(self, state: JsonObject) -> ProjectDocument: ...
    def select_plate(self, state: JsonObject, plate: int) -> JsonObject: ...
    def commit(self, state: JsonObject, document: ProjectDocument, operations: list[JsonObject],
               results: list[JsonValue], engine: EngineIdentity) -> JsonObject: ...

class ProjectSlicer(Protocol):
    @property
    def engine(self) -> EngineIdentity: ...
    def slice_3mf(self, path: str, plate: int, force: bool = False,
                  allow_newer_file: bool = True) -> JsonObject: ...

class NativeEditing(Protocol):
    def execute(self, document: ProjectDocument, name: str, arguments: JsonObject,
                state: JsonObject) -> JsonValue: ...
