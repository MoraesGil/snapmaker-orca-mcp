"""Typed preset storage and identity capabilities."""
from __future__ import annotations
from typing import Protocol, TypedDict
from ...domain.types.json import JsonObject

class PresetRecord(TypedDict):
    name: str
    type: str
    source: str
    path: str
    sha256: str
    raw: JsonObject
    read_only: bool

class EngineIdentity(Protocol):
    def verify(self) -> None: ...
    def identity(self) -> JsonObject: ...

class PresetRepository(Protocol):
    def records(self) -> list[PresetRecord]: ...
    def draft_path(self, kind: str, name: str) -> str: ...
    def write(self, location: str, doc: JsonObject, previous: PresetRecord | None = None) -> None: ...
    def remove(self, rec: PresetRecord, rollback_path: str | None = None, action: str = 'delete') -> None: ...

class PresetCatalog(Protocol):
    def get_preset_config(self, type: str, name: str) -> JsonObject: ...
    def list_presets(self, type: str | None = None, include_system: bool = False) -> JsonObject: ...
    def preset_keys(self, type: str) -> set[str]: ...
    def save_preset(self, type: str, name: str, config: JsonObject, detach: bool = False,
                    allow_custom_gcode: bool = False) -> JsonObject: ...
