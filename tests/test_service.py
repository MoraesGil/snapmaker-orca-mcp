import hashlib
import json
import os
import sys
import zipfile
from pathlib import Path

import pytest


SOURCE_COMMIT = "1" * 40
NEXT_COMMIT = "2" * 40
GCODE_1 = "; generated by Snapmaker Orca test boundary\nG1 X1 Y2 Z0.2 E0.3 F1200\n; CONFIG_BLOCK_START\n; layer_height = 0.2\n; CONFIG_BLOCK_END\n"
GCODE_2 = "G1 X3 Y4 Z0.2 E0.5 F1200\n"


def make_project(path, post_process=None):
    with zipfile.ZipFile(path, "w") as z:
        z.writestr("3D/3dmodel.model", '<model><resources/><build/></model>')
        z.writestr("Metadata/project_settings.config", json.dumps({"layer_height": "0.2", "post_process": post_process or []}))
        z.writestr("Metadata/plate_1.gcode", "G1 X999 E999 ; old embedded data\n")
    return path


def boundary(tmp_path):
    # External native process is deliberately replaced here; these tests cover
    # the wrapper boundary, not slicing algorithms or GUI/CLI equivalence.
    from snapmaker_slicer_mcp.engine import Engine
    from snapmaker_slicer_mcp.service import Slicer

    binary = tmp_path / "engine" / ("Contents/MacOS/native-boundary" if sys.platform == "darwin" else
                                  "native-boundary" if os.name == "nt" else "bin/native-boundary")
    binary.parent.mkdir(parents=True)
    binary.write_text(f'''#!{sys.executable}
import argparse, json, os, pathlib, sys, time
p=argparse.ArgumentParser()
p.add_argument('--slice',type=int,required=True)
p.add_argument('--outputdir',required=True)
p.add_argument('--datadir',required=True)
p.add_argument('--allow-newer-file',action='store_true')
p.add_argument('--export-settings',required=True)
p.add_argument('project')
a=p.parse_args()
assert 'DISPLAY' not in os.environ and 'WAYLAND_DISPLAY' not in os.environ
assert 'SNAPMAKER_ORCA_ALLOW_NEWER_FILE' not in os.environ
out=pathlib.Path(a.outputdir)
mode=pathlib.Path(__file__).with_suffix('.mode')
value=mode.read_text() if mode.exists() else ''
if value=='sleep': time.sleep(10)
if value=='fail': sys.exit(7)
assert pathlib.Path(a.project).read_bytes()
for n,code in ((1,{GCODE_1!r}),(2,{GCODE_2!r})):
    if a.slice in (0,n): (out/f'plate_{{n}}.gcode').write_text(code)
pathlib.Path(a.export_settings).write_text(json.dumps({{'layer_height':'0.2'}}))
''')
    binary.chmod(0o755)
    resources = tmp_path / "engine" / ("Contents/Resources" if sys.platform == "darwin" else "resources")
    resources.mkdir()
    (resources / "profile.json").write_text('{"layer_height":"0.2"}')
    manifest = Engine.bind(binary, SOURCE_COMMIT, resources)
    engine = Engine(manifest)
    return Slicer(engine, tmp_path / "artifacts"), binary


def test_slice_preserves_source_and_all_new_plate_outputs(tmp_path, monkeypatch):
    slicer, _ = boundary(tmp_path)
    source = make_project(tmp_path / "input.3mf")
    original = source.read_bytes()
    monkeypatch.setenv("DISPLAY", ":99")
    monkeypatch.setenv("WAYLAND_DISPLAY", "wayland-0")
    result = slicer.slice_3mf(str(source))
    assert result["status"] == "ready"
    assert result["cached"] is False
    assert [p["plate"] for p in result["plates"]] == [1, 2]
    assert Path(result["plates"][0]["gcode_path"]).read_text() == GCODE_1
    assert Path(result["source"]["path"]).read_bytes() == original == source.read_bytes()
    assert result["source"]["sha256"] == hashlib.sha256(original).hexdigest()
    props = json.loads(Path(result["props_path"]).read_text())
    assert props["native_global"]["layer_height"] == "0.2"
    assert props["plate_config"]["1"]["layer_height"] == "0.2"
    assert props["fallback_profile"] is None


def test_cache_is_verified_and_force_and_corruption_run_native_again(tmp_path):
    slicer, binary = boundary(tmp_path)
    source = make_project(tmp_path / "input.3mf")
    first = slicer.slice_3mf(str(source), plate=2)
    binary.with_suffix('.mode').write_text('fail')
    second = slicer.slice_3mf(str(source), plate=2)
    assert second["cached"] is True
    assert second["job_id"] == first["job_id"]
    with pytest.raises(RuntimeError): slicer.slice_3mf(str(source), plate=2, force=True)
    Path(first["plates"][0]["gcode_path"]).write_text('corrupt')
    with pytest.raises(RuntimeError): slicer.slice_3mf(str(source), plate=2)
    binary.with_suffix('.mode').unlink()
    third = slicer.slice_3mf(str(source), plate=2)
    assert third["cached"] is False
    assert third["job_id"] != first["job_id"]
    assert [p["plate"] for p in third["plates"]] == [2]


def test_failures_are_not_cached_and_timeouts_leave_diagnostics(tmp_path):
    slicer, binary = boundary(tmp_path)
    source = make_project(tmp_path / "input.3mf")
    binary.with_suffix('.mode').write_text('fail')
    with pytest.raises(RuntimeError): slicer.slice_3mf(str(source))
    binary.with_suffix('.mode').write_text('sleep')
    slicer.timeout = 0.15
    with pytest.raises(TimeoutError): slicer.slice_3mf(str(source))
    assert not list((slicer.root / "cache").glob("*.json"))
    assert len(list((slicer.root / "runs").glob("*/engine.log"))) == 2


def test_source_recovery_requires_matching_gcode_and_intact_source(tmp_path):
    slicer, _ = boundary(tmp_path)
    source = make_project(tmp_path / "input.3mf")
    result = slicer.slice_3mf(str(source), plate=1)
    recovered = slicer.recover_3mf(result["plates"][0]["gcode_path"])
    assert recovered["kind"] == "source_recovery"
    assert recovered["reconstructed"] is False
    assert Path(recovered["path"]).read_bytes() == source.read_bytes()
    unknown = tmp_path / "unrelated.gcode"
    unknown.write_text('G1 X9 E9\n')
    with pytest.raises(ValueError): slicer.recover_3mf(str(unknown))
    Path(recovered["path"]).write_bytes(b'corrupt')
    with pytest.raises(ValueError): slicer.recover_3mf(result["plates"][0]["gcode_path"])


def test_resources_read_only_generated_job_ranges_and_reject_traversal(tmp_path):
    slicer, _ = boundary(tmp_path)
    result = slicer.slice_3mf(str(make_project(tmp_path / "input.3mf")), plate=1)
    assert slicer.read_lines(result["job_id"], 1, 2, 1)["lines"] == ["G1 X1 Y2 Z0.2 E0.3 F1200"]
    with pytest.raises(ValueError): slicer.read_lines("../outside", 1, 1, 20)
    with pytest.raises(ValueError): slicer.read_lines(result["job_id"], 1, 1, 1000000)


def test_settings_changes_and_engine_identity_invalidate_reuse(tmp_path):
    slicer, _ = boundary(tmp_path)
    source = make_project(tmp_path / "input.3mf")
    first = slicer.slice_3mf(str(source))
    make_project(source, post_process=['external-command'])
    with pytest.raises(ValueError): slicer.slice_3mf(str(source))
    make_project(source)
    slicer.engine.manifest["source_commit"] = NEXT_COMMIT
    assert slicer.slice_3mf(str(source))["job_id"] != first["job_id"]


def test_update_check_reports_notice_and_never_changes_bound_engine(tmp_path, monkeypatch):
    slicer, binary = boundary(tmp_path)
    before = binary.read_bytes()
    monkeypatch.setattr(slicer.engine, "_remote_head", lambda: NEXT_COMMIT)
    status = slicer.engine.status(check_remote=True)
    assert status["update_available"] is True
    assert status["source_commit"] == SOURCE_COMMIT
    assert status["upstream_commit"] == NEXT_COMMIT
    assert status["notices"]
    assert binary.read_bytes() == before
    monkeypatch.setattr(slicer.engine, "_remote_head", lambda: (_ for _ in ()).throw(OSError("offline")))
    assert slicer.engine.status(check_remote=True)["update_check"] == "unavailable"


def test_binding_rejects_changed_executable_or_resources(tmp_path):
    slicer, binary = boundary(tmp_path)
    from snapmaker_slicer_mcp.engine import Engine
    manifest = dict(slicer.engine.manifest)
    binary.write_text('different executable')
    with pytest.raises(ValueError): Engine(manifest)


@pytest.mark.parametrize('asset', ['binary', 'resources'])
def test_running_server_rejects_engine_drift_before_cache_or_native(tmp_path, asset):
    slicer, binary = boundary(tmp_path)
    source = make_project(tmp_path / 'input.3mf')
    slicer.slice_3mf(str(source))
    path = binary if asset == 'binary' else Path(slicer.engine.manifest['resources']) / 'profile.json'
    path.write_text(path.read_text() + ' ')
    with pytest.raises(ValueError, match='Engine.*changed'):
        slicer.slice_3mf(str(source))
    with pytest.raises(ValueError, match='Engine.*changed'):
        slicer.slice_3mf(str(source), force=True)


def test_binding_rejects_resources_not_used_by_native_package(tmp_path):
    from snapmaker_slicer_mcp.engine import Engine
    slicer, binary = boundary(tmp_path)
    unrelated = tmp_path / 'unrelated-resources'
    unrelated.mkdir()
    with pytest.raises(ValueError, match='resources.*layout'):
        Engine.bind(binary, SOURCE_COMMIT, unrelated)


def test_source_recovery_ignores_unrelated_corrupt_job_records(tmp_path):
    slicer, _ = boundary(tmp_path)
    result = slicer.slice_3mf(str(make_project(tmp_path / 'input.3mf')), plate=1)
    for job_id, data in [('a' * 32, '{'), ('b' * 32, '{}'), ('c' * 32, '[]'),
                         ('d' * 32, '{"job_id":"' + 'd' * 32 + '","plates":[null],"source":{}}')]:
        broken = slicer.root / 'runs' / job_id
        broken.mkdir()
        (broken / 'result.json').write_text(data)
    recovered = slicer.recover_3mf(result['plates'][0]['gcode_path'])
    assert recovered['sha256'] == result['source']['sha256']


def test_swapped_cache_pointer_cannot_return_a_different_source_or_plate(tmp_path):
    slicer, _ = boundary(tmp_path)
    source = make_project(tmp_path / 'input.3mf')
    first = slicer.slice_3mf(str(source), plate=1)
    pointer = next((slicer.root / 'cache').glob('*.json'))
    other = slicer.slice_3mf(str(source), plate=2)
    pointer.write_text(json.dumps({'job_id': other['job_id']}))
    result = slicer.slice_3mf(str(source), plate=1)
    assert result['cached'] is False
    assert result['job_id'] != first['job_id']
    assert [p['plate'] for p in result['plates']] == [1]


def test_cache_rejects_manifest_with_a_generated_plate_removed(tmp_path):
    slicer, _ = boundary(tmp_path)
    source = make_project(tmp_path / 'input.3mf')
    result = slicer.slice_3mf(str(source))
    manifest = slicer.root / 'runs' / result['job_id'] / 'result.json'
    partial = json.loads(manifest.read_text())
    partial['plates'].pop()
    manifest.write_text(json.dumps(partial))
    repeated = slicer.slice_3mf(str(source))
    assert repeated['cached'] is False
    assert len(repeated['plates']) == 2


def test_engine_rejects_linux_resource_resolution_change_after_binding(tmp_path, monkeypatch):
    import snapmaker_slicer_mcp.engine as module
    monkeypatch.setattr(module.sys, 'platform', 'linux')
    binary = tmp_path / 'engine/bin/Release/native'
    binary.parent.mkdir(parents=True)
    binary.write_text('#!/bin/sh\nexit 0\n')
    binary.chmod(0o755)
    fallback = tmp_path / 'engine/resources'
    fallback.mkdir()
    (fallback / 'profile.json').write_text('{}')
    engine = module.Engine(module.Engine.bind(binary, SOURCE_COMMIT, fallback))
    (tmp_path / 'engine/bin/resources').mkdir()
    with pytest.raises(ValueError, match='Engine.*changed'):
        engine.verify()


def test_newer_file_compatibility_is_recorded_and_changes_cache_identity(tmp_path, monkeypatch):
    slicer, _ = boundary(tmp_path)
    source = make_project(tmp_path / "input.3mf")
    allowed = slicer.slice_3mf(str(source))
    monkeypatch.setenv('SNAPMAKER_ORCA_ALLOW_NEWER_FILE', '1')
    strict = slicer.slice_3mf(str(source), allow_newer_file=False)
    assert allowed["compatibility_flags"]["allow_newer_file"] is True
    assert strict["compatibility_flags"]["allow_newer_file"] is False
    assert allowed["job_id"] != strict["job_id"]


def test_config_block_preserves_empty_values_and_values_containing_equals(tmp_path):
    from snapmaker_slicer_mcp.service import gcode_properties
    path = tmp_path / 'native.gcode'
    path.write_text('; CONFIG_BLOCK_START\n; empty_value = \n; expression = x = y\n; CONFIG_BLOCK_END\n')
    assert gcode_properties(path) == {"empty_value": "", "expression": "x = y"}
